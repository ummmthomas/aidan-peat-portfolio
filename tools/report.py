#!/usr/bin/env python3
"""Write the rebuild's tracking docs from the current sources.

    python3 tools/report.py

docs/rebuild/03-media-map.md     where every file in assets/freight/i/ is used
docs/rebuild/04-placeholders.md  every [[FACT/METRIC/QUOTE: ...]] still to fill,
                                 grouped by page

Run it again after filling placeholders or moving media, and the docs update.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FREIGHT = os.path.join(ROOT, 'assets', 'freight', 'i')
PLACEHOLDER = re.compile(r'\[\[(FACT|METRIC|QUOTE): ([^\]]+)\]\]')

# Files deliberately left out of every page, and why.
UNPLACED = {
    'V2982998910402254339518073602343': "Cargo's template placeholder photo (flagged `is_placeholder` in Cargo's data), not Aidan's work. It was the share image on five pages and has been replaced there.",
    'R3172555047214688550948529635609': "Screenshot of the old homepage, which Cargo made for link previews. It no longer represents the site.",
    'R3171074401998566312648511979801': "Byte-identical duplicate of Me.png (N3171073763…), which is on the About page.",
}
SITE_FURNITURE = {
    'N3172352635832780962982002032921': 'favicon, every page',
}


def load():
    with open(os.path.join(ROOT, 'site-src', 'state.json'), encoding='utf-8') as f:
        state = json.load(f)
    with open(os.path.join(ROOT, 'site-src', 'routes.json'), encoding='utf-8') as f:
        routes = json.load(f)['routes']
    pages = []
    for pid in state['structure']['byParent']['root']:
        page = state['pages']['byId'][pid]
        src = page['content'][1:] if page['content'].startswith('@') else None
        body = open(os.path.join(ROOT, src), encoding='utf-8').read() if src else page['content']
        pages.append((page['purl'], page['title'], body))
    return pages, routes


def media_map(pages, routes):
    uses = {}
    for purl, title, body in pages:
        for h in re.findall(r'hash="([A-Za-z0-9]+)"', body):
            uses.setdefault(h, [])
            if purl not in uses[h]:
                uses[h].append(purl)
    shares = {}
    for r in routes:
        m = re.search(r'freight/i/([^/]+)/', r['image'])
        if m:
            shares.setdefault(m.group(1), []).append(r['file'].removesuffix('.html'))
    on_disk = sorted(os.listdir(FREIGHT))
    lines = ['# Media map', '',
             'Where every file in `assets/freight/i/` is used after the rebuild. Generated by `tools/report.py`.', '',
             '| Hash | File | Shown on | Share image for |', '| --- | --- | --- | --- |']
    unplaced = []
    for h in on_disk:
        name = os.listdir(os.path.join(FREIGHT, h))[0]
        shown = ', '.join(f'`{p}`' for p in uses.get(h, [])) or SITE_FURNITURE.get(h, '')
        share = ', '.join(f'`{p}`' for p in shares.get(h, []))
        if not shown and share:
            shown = 'share image only'
        elif not shown:
            unplaced.append((h, name))
            shown = '**unplaced**'
        lines.append(f'| `{h[:10]}` | {name} | {shown} | {share} |')
    videos = sorted(h for h in uses if h not in on_disk)
    lines += ['', '## Embedded videos', '', '| Hash | Shown on |', '| --- | --- |']
    lines += [f'| `{h[:10]}` | ' + ', '.join(f'`{p}`' for p in uses[h]) + ' |' for h in videos]
    lines += ['', '## Unplaced, with reasons', '']
    for h, name in unplaced:
        lines.append(f'- `{h[:10]}` {name}: ' + UNPLACED.get(h, '**no reason recorded: place it or add a reason in tools/report.py**'))
    total = len(on_disk)
    lines += ['', f'{total} files: {total - len(unplaced)} placed or used as site furniture, {len(unplaced)} unplaced. No file was deleted.', '']
    return '\n'.join(lines)


def placeholders(pages, routes):
    lines = ['# Placeholders for Aidan', '',
             'Everything the site still needs from Aidan, grouped by page. Generated by `tools/report.py` from `site-src/`.', '',
             'How to fill one: search `site-src/pages/` for the text and replace the whole `[[...]]`. Inside a `<span class="ph">`, also remove the span. In an impact stat or quote, the value lives in `data-value` / `data-quote` / `data-cite`, and the stat appears on the page once it no longer starts with `[[`. Then run `python3 tools/build.py`.', '']
    total = 0
    for purl, title, body in pages:
        found = []
        for kind, text in PLACEHOLDER.findall(body):
            item = f'{kind}: {text.strip()}'
            if item not in found:
                found.append(item)
        if not found:
            continue
        total += len(found)
        lines += [f'## {title} (`{purl}`)', '']
        lines += [f'- [ ] `[[{item}]]`' for item in found]
        lines.append('')
    lines += ['## Public facts used as written (confirm with Aidan)', '',
              'These come from primary sources, so they appear as plain text rather than placeholders.', '',
              '- [ ] Shenzhen: Sea World Culture and Arts Center, Shekou; 17 June – 15 October 2023; Pearl Lam Galleries and COEXIST; 40+ works; Colbert\'s first show in South China. Source: [Pearl Lam press release](https://www.pearllam.com/wp-content/uploads/2023/06/Press-Release-EN.pdf)',
              '- [ ] ASUS: Vivobook 13 Slate OLED Philip Colbert Edition announced May 2022 as one of two limited artist editions; 13.3-inch detachable OLED; bundle with lobster stylus holder and shoelaces. Source: [ASUS press release](https://press.asus.com/news/press-releases/193)',
              '- [ ] About and homepage: that Aidan worked on the Johnnie Walker, adidas and ASUS collaborations. The old homepage listed them as his work, but the site never said what he did.',
              '']
    lines.insert(4, f'{total} placeholders across {sum(1 for l in lines if l.startswith("## ")) - 1} pages.\n')
    return '\n'.join(lines)


def main():
    pages, routes = load()
    out = os.path.join(ROOT, 'docs', 'rebuild')
    for name, text in (('03-media-map.md', media_map(pages, routes)), ('04-placeholders.md', placeholders(pages, routes))):
        with open(os.path.join(out, name), 'w', encoding='utf-8') as f:
            f.write(text)
        print('Wrote docs/rebuild/' + name)


if __name__ == '__main__':
    main()
